#include "calculator.h"

double add(double val1,double val2)
{
    return val1+val2;
}
double subtract(double val1,double val2)
{
    return val1-val2;
}

double multiply(double val1,double val2)
{
    return val1*val2;
}

double divide(double val1,double val2)
{
    return val1/val2;
}
